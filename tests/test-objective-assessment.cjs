const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const assert = require('node:assert/strict');
const source = fs.readFileSync(path.join(__dirname, '../scripts/skills-assessment.js'), 'utf8');
const context = {};
vm.runInNewContext(source.slice(0, source.indexOf('const key =')) + '\nglobalThis.bank={items,tasks};})();', context);
const { items, tasks } = context.bank;
assert.equal(items.length, 50);
assert.equal(new Set(items.map(item => item.id)).size, 50);
assert.equal(tasks.length, 6);
for (const skill of new Set(items.map(item => item.skill))) assert.equal(items.filter(item => item.skill === skill).length, 5);
assert.ok(items.every(item => item.key >= 0 && item.key <= 3));
const state = { answers: Object.fromEntries(items.map(item => [item.id,item.key])), practical: Object.fromEntries(tasks.map(task => [task.id,'Test response'])), coding: { code: 'test', runs: 1 } };
const completionContext = { items, tasks, state, starterCode: 'starter' };
vm.runInNewContext(source.slice(source.indexOf('function completion()'), source.indexOf('function updateEvidence()')) + '\nglobalThis.complete=completion;', completionContext);
assert.equal(completionContext.complete().quizAnswered, 50);
assert.equal(completionContext.complete().practicalCompleted.length, 6);
state.answers.Q01 = 99; state.practical.P1 = ' '.repeat(2); state.practical.P2 = 'a'.repeat(2501);
assert.equal(completionContext.complete().quizAnswered, 49);
assert.equal(completionContext.complete().practicalCompleted.length, 4);
let receive, result;
const runner = fs.readFileSync(path.join(__dirname, '../scripts/research-code-runner.html'), 'utf8').split('<script>')[1].split('</script>')[0];
vm.runInNewContext(runner, { window: { addEventListener: (_,callback) => { receive=callback; } }, parent: { postMessage: value => { result=value; } } });
receive({ data: { type: 'run', token: 'test', code: 'function larger(a,b){return Math.max(a,b)}' } });
assert.equal(result.results.length, 8);
assert.ok(result.results.every(item => item.passed));
receive({ data: { type: 'run', token: 'test', code: 'function larger(a,b){return Math.min(a,b)}' } });
assert.ok(result.results.some(item => !item.passed));
console.log('PASS: question bank, domain counts, invalid/oversized answers and eight coding checks.');
